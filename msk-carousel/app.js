// Missing screenshot -> clearly labelled placeholder (never a fake page).
const toPlaceholder = (img) => {
  const ph = document.createElement('div');
  ph.className = 'ph';
  ph.innerHTML = `<div>لقطة شاشة: ${img.alt || ''}<small>${img.getAttribute('src')}</small></div>`;
  img.replaceWith(ph);
};
document.querySelectorAll('.screen img').forEach((img) => {
  if (img.complete && img.naturalWidth === 0) toPlaceholder(img);
  else img.addEventListener('error', () => toPlaceholder(img));
});

// Shrink devices inside a .stage so they never overflow the space left under the text.
window.fitStages = () => {
  document.querySelectorAll('.stage, .fitbox').forEach((stage) => {
    const avail = stage.clientHeight;
    stage.querySelectorAll(':scope > .laptop, :scope > .browser, :scope > .phone:not([style*="absolute"])').forEach((dev) => {
      for (let k = 0; k < 3; k++) {
        const h = dev.offsetHeight;
        if (h <= avail + 1) break;
        dev.style.width = (dev.offsetWidth * avail) / h + 'px';
      }
    });
  });
};
window.addEventListener('load', () => document.fonts.ready.then(window.fitStages));
